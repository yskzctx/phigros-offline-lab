#!/usr/bin/env python3
"""Generate the on-device hook tables from a version profile.

`src/expected-hooks.h` and `src/skin-hooks.h` are the truth the native code compiles
in: they carry each hook's RVA, its 16-byte prologue and the relocation mask. A
profile in `profiles/` describes the same facts for one game build. Keeping both by
hand is how a profile can claim one offset while the shipped binary hooks another.

This tool emits the headers from a profile, so a new game version becomes:

    python tools/recover_profile.py ... --out profiles/161.json
    python tools/audit_profile.py --profile profiles/161.json --reference-so ... --target-so ...
    python tools/gen_hooks_header.py --profile profiles/161.json --check      # or --write

`--check` exits non-zero when the headers disagree with the profile, which is what CI
should run; `--write` regenerates them.

Usage:
    python tools/gen_hooks_header.py --profile profiles/157.json --check
    python tools/gen_hooks_header.py --profile profiles/161.json --write
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# Which profile hooks belong in which header, in the order the C arrays expect.
EXPECTED_HOOKS = ['click', 'drag', 'flick', 'hold', 'record', 'perfect', 'result', 'miss', 'good']
SKIN_HOOKS = [
    'skinClickControl$$NoteMove',
    'skinDragControl$$NoteMove',
    'skinFlickControl$$NoteMove',
    'skinHoldControl$$NoteMove',
]

HEADER_TEMPLATE = """\
/* Generated by tools/gen_hooks_header.py from {profile} - do not edit by hand.
 *
 * Version {version_name} ({version_code}), libil2cpp.so sha256 {sha}
 *
 * Each entry is {{name, rva, 16-byte prologue, relocation mask}}. The prologue is
 * matched byte for byte at the RVA to prove the hook is landing on the intended
 * function; the mask marks bytes that encode an address and are therefore compared
 * loosely.
 */
#ifndef PHIGROS_HOOKSPEC_DEFINED
#define PHIGROS_HOOKSPEC_DEFINED
struct HookSpec {{ const char *name; unsigned long rva; unsigned char prefix[16]; unsigned relocate_mask; }};
#endif
static const struct HookSpec hooks[{count}] = {{
{entries}
}};
"""
# skin-hooks.h also carries the auxiliary Unity helper RVAs that skins.c calls
# directly. They are not hooks, so a profile does not describe them; the generator
# preserves whatever the existing header declares so a regeneration cannot silently
# drop them.
AUX_DEFINE_MARKER = '#define '

SKIN_TEMPLATE = """\
/* Generated by tools/gen_hooks_header.py from {profile} - do not edit by hand.
 *
 * Version {version_name} ({version_code}), libil2cpp.so sha256 {sha}
 *
 * The four NoteMove hooks are matched by prologue; the #define block below carries
 * the auxiliary Unity helper RVAs skins.c calls directly, which a profile does not
 * describe and therefore are carried over unchanged.
 */
struct HookSpec {{const char *name;unsigned long rva;unsigned char prefix[16];unsigned relocate_mask;}};
static const struct HookSpec skin_hooks[]={{
{entries}
}};
{aux}"""


def c_bytes(prefix: str) -> str:
    raw = bytes.fromhex(prefix)
    return ','.join(f'0x{b:02x}' for b in raw)


def build(profile: dict, names: list[str], profile_path: Path) -> str:
    hooks = profile['hooks']
    missing = [name for name in names if name not in hooks]
    if missing:
        raise SystemExit(f'{profile_path} has no offsets for: {missing}')
    lines = []
    for name in names:
        hook = hooks[name]
        # The C arrays name the skin hooks without the profile's `skin` prefix, since
        # the file is already about skin hooks.
        label = name[len('skin'):] if name.startswith('skin') else name
        lines.append('{{"{}",0x{:x},{{{}}},{}}},'.format(
            label, int(hook['rva']), c_bytes(hook['prefix']),
            int(hook.get('relocateMask', 0))))
    return HEADER_TEMPLATE.format(
        profile=profile_path.name,
        version_name=profile.get('versionName', '?'),
        version_code=profile.get('versionCode', '?'),
        sha=profile.get('il2cppSha256', '?'),
        count=len(names),
        entries='\n'.join(lines),
    )


def build_skin(profile: dict, profile_path: Path, aux_block: str) -> str:
    """Build skin-hooks.h, carrying over the auxiliary #define block verbatim."""
    hooks = profile['hooks']
    missing = [name for name in SKIN_HOOKS if name not in hooks]
    if missing:
        raise SystemExit(f'{profile_path} has no offsets for: {missing}')
    lines = []
    for name in SKIN_HOOKS:
        hook = hooks[name]
        label = name[len('skin'):] if name.startswith('skin') else name
        lines.append('{{"{}",0x{:x},{{{}}},{}}},'.format(
            label, int(hook['rva']), c_bytes(hook['prefix']),
            int(hook.get('relocateMask', 0))))
    return SKIN_TEMPLATE.format(
        profile=profile_path.name,
        version_name=profile.get('versionName', '?'),
        version_code=profile.get('versionCode', '?'),
        sha=profile.get('il2cppSha256', '?'),
        entries='\n'.join(lines),
        aux=aux_block,
    )


def aux_defines(path: Path) -> str:
    """Return the trailing `#define` block of an existing skin header."""
    if not path.is_file():
        raise SystemExit(f'{path} is missing, so its auxiliary #define block cannot be preserved')
    lines = [line for line in path.read_text(encoding='utf-8').splitlines()
             if line.startswith(AUX_DEFINE_MARKER)]
    if not lines:
        raise SystemExit(f'{path} has no auxiliary #define block to preserve')
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--profile', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='fail if headers differ')
    parser.add_argument('--write', action='store_true', help='regenerate headers')
    parser.add_argument('--expected-header', type=Path, default=REPO / 'src' / 'expected-hooks.h')
    parser.add_argument('--skin-header', type=Path, default=REPO / 'src' / 'skin-hooks.h')
    parser.add_argument('--aux-defines-from', type=Path,
                        help='header to copy the skin auxiliary #define block from '
                             '(default: --skin-header)')
    args = parser.parse_args()

    if not args.check and not args.write:
        parser.error('pass --check or --write')

    profile = json.loads(args.profile.read_text(encoding='utf-8'))
    if not profile.get('complete'):
        print(f'{args.profile.name} is not complete; refusing to generate headers from it')
        return 1

    # The auxiliary Unity helper RVAs live only in the header, so they are carried
    # over from an existing one. A brand-new version reads them from the current
    # header while writing somewhere else (--skin-header points at the new file).
    aux_source = args.aux_defines_from or args.skin_header
    if not aux_source.is_file() and (REPO / 'src' / 'skin-hooks.h').is_file():
        aux_source = REPO / 'src' / 'skin-hooks.h'

    generated = {
        args.expected_header: build(profile, EXPECTED_HOOKS, args.profile),
        args.skin_header: build_skin(profile, args.profile, aux_defines(aux_source)),
    }

    if args.write:
        for path, text in generated.items():
            path.write_text(text, encoding='utf-8')
            try:
                shown = path.relative_to(REPO)
            except ValueError:
                shown = path
            print(f'wrote {shown}')
        return 0

    failures = 0
    for path, text in generated.items():
        current = path.read_text(encoding='utf-8') if path.is_file() else ''
        try:
            shown = path.relative_to(REPO)
        except ValueError:
            shown = path
        if current == text:
            print(f'PASS {shown} matches {args.profile.name}')
        else:
            print(f'FAIL {shown} differs from {args.profile.name}')
            failures += 1
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
